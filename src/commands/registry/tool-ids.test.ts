/**
 * Current generated inventory from the local SDK operation set. The SDK
 * schema/operation branch is intentionally unreleased, so this count is a
 * local integration gate and must be refreshed when that branch changes.
 */
const EXPECTED_TOOL_COUNT = 666;

describe('tool id inventory', () => {
  it('keeps every T2a baseline tool id (superset — no id removed or renamed)', () => {
    const ids = new Set(allCommands().map((c) => c.id));
    for (const id of BASELINE_TOOL_IDS) {
      expect(ids.has(id)).toBe(true);
    }
  });

  it('keeps the released generated ids and a unique current inventory', () => {
    const ids = allCommands().map((c) => c.id);
    expect(new Set(ids).size).toBe(ids.length);
    for (const id of Object.values(RELEASED_GENERATED_TOOL_IDS)) {
      expect(ids).toContain(id);
    }
  });

  it('keeps the current local SDK inventory count', () => {
    expect(allCommands().length).toBe(EXPECTED_TOOL_COUNT);
  });
});
